import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { AdviceResponse } from "../../shared/contracts";
import { ResultsView } from "./ResultsView";

const response: AdviceResponse = {
  adviceMarkdown: [
    "## Core advice",
    "",
    "Lead with the most grounded version of the truth.",
    "",
    "## Why this advice",
    "",
    "It balances honesty with proportionality.",
    "",
    "## Watch for",
    "",
    "Avoid turning uncertainty into accusation.",
    "",
    "## Next steps",
    "",
    "Confirm what you know before you escalate."
  ].join("\n"),
  profile: {
    outcomesPrinciples: -0.15,
    individualCollective: 0.4,
    reasonIntuition: -0.2
  },
  nearestProfiles: [
    {
      id: "gilligan-care-ethics",
      name: "Care Ethics",
      representative: "Carol Gilligan",
      group: "contemporary",
      voiceStyle: "in-the-spirit",
      voiceBrief: "brief",
      speaker: { years: "born 1936", region: "United States", traditions: "Care ethics" },
      coordinates: {
        outcomesPrinciples: -0.1,
        individualCollective: 0.8,
        reasonIntuition: 0.2
      },
      summary: "Relational and context-aware.",
      exampleConcerns: ["care"],
      distance: 0.3,
      whyItFits: "It stays attentive to harm, trust, and relationships."
    },
    {
      id: "aristotle-virtue-ethics",
      name: "Virtue Ethics",
      representative: "Aristotle",
      group: "ancient",
      voiceStyle: "first-person",
      voiceBrief: "brief",
      speaker: { years: "384–322 BCE", region: "Ancient Greece", traditions: "Virtue ethics" },
      coordinates: {
        outcomesPrinciples: 0.2,
        individualCollective: 0.1,
        reasonIntuition: 0
      },
      summary: "Character-centered.",
      exampleConcerns: ["character"],
      distance: 0.5,
      whyItFits: "It is nearby on practical judgment."
    }
  ],
  safetyMode: "standard",
  modelsUsed: ["openai:gpt-5.4-mini"]
};

describe("ResultsView", () => {
  const originalInnerWidth = window.innerWidth;
  const clientWidthDescriptor = Object.getOwnPropertyDescriptor(
    HTMLElement.prototype,
    "clientWidth"
  );
  const scrollWidthDescriptor = Object.getOwnPropertyDescriptor(
    HTMLElement.prototype,
    "scrollWidth"
  );

  let measuredClientWidth = 1200;
  let measuredScrollWidth = 900;

  beforeEach(() => {
    window.innerWidth = 1280;
    measuredClientWidth = 1200;
    measuredScrollWidth = 900;

    Object.defineProperty(HTMLElement.prototype, "clientWidth", {
      configurable: true,
      get() {
        return this.classList.contains("results-tabs-measure") ? measuredClientWidth : 0;
      }
    });

    Object.defineProperty(HTMLElement.prototype, "scrollWidth", {
      configurable: true,
      get() {
        return this.classList.contains("results-tabs-measure") ? measuredScrollWidth : 0;
      }
    });
  });

  afterEach(() => {
    cleanup();
    window.innerWidth = originalInnerWidth;

    if (clientWidthDescriptor) {
      Object.defineProperty(HTMLElement.prototype, "clientWidth", clientWidthDescriptor);
    }

    if (scrollWidthDescriptor) {
      Object.defineProperty(HTMLElement.prototype, "scrollWidth", scrollWidthDescriptor);
    }
  });

  it.each([
    { models: ["anthropic:claude-haiku-5-5", "openai:gpt-5.4-mini"], expected: "> Advice model: GPT-5.4 Mini (openai:gpt-5.4-mini)", planner: true },
    { models: ["fallback:openai:gpt-5.4-mini"], expected: "> Advice model: GPT-5.4 Mini (openai:gpt-5.4-mini)", planner: false },
    { models: ["local-safety"], expected: "> Generated by: local safety response (no AI model)", planner: false }
  ])("exports the actual generation models: $models", async ({ models, expected, planner }) => {
    const write = vi.fn().mockResolvedValue(undefined);
    vi.stubGlobal("showSaveFilePicker", vi.fn().mockResolvedValue({
      createWritable: async () => ({ write, close: async () => undefined })
    }));
    try {
      render(<ResultsView response={{ ...response, modelsUsed: models }} dilemma="A difficult choice"
        explanationLevel="general" personaMode="personalized" onRestart={() => undefined} />);
      fireEvent.click(screen.getByRole("tab", { name: "Export" }));
      fireEvent.click(screen.getByRole("button", { name: "Save as markdown file" }));
      await waitFor(() => expect(write).toHaveBeenCalled());
      const markdown = write.mock.calls[0][0];
      expect(markdown).toContain(expected);
      expect(markdown.includes("> Planner model: Claude Haiku 5.5 (anthropic:claude-haiku-5-5)")).toBe(planner);
    } finally {
      vi.unstubAllGlobals();
    }
  });

  it("switches to the hamburger menu when the tab row overflows", async () => {
    const { container } = render(
      <ResultsView
        response={response}
        dilemma="I heard a rumor about a colleague and do not know whether to raise it."
        explanationLevel="general"
        personaMode="personalized"
        onRestart={() => undefined}
      />
    );

    const desktopNav = container.querySelector(
      "[role=tablist].results-tabs-desktop"
    );
    const mobileNav = container.querySelector("nav.results-tabs-mobile");

    await waitFor(() => {
      expect(screen.queryByRole("button", { name: /^Advice sections/ })).not.toBeInTheDocument();
    });

    expect(screen.getByRole("tab", { name: "Reasoning" })).toBeInTheDocument();
    expect(desktopNav).not.toHaveAttribute("hidden");
    expect(mobileNav).toHaveAttribute("hidden");

    measuredClientWidth = 760;
    measuredScrollWidth = 980;
    fireEvent(window, new Event("resize"));

    await waitFor(() => {
      expect(screen.getByRole("button", { name: /^Advice sections/ })).toBeInTheDocument();
    });

    expect(screen.queryByRole("tab", { name: "Reasoning" })).not.toBeInTheDocument();
    expect(desktopNav).toHaveAttribute("hidden");
    expect(mobileNav).not.toHaveAttribute("hidden");
  });

  it("shows the speaker card and speaker tab only when a philosopher voice was used", async () => {
    const props = {
      dilemma: "I heard a rumor about a colleague and do not know whether to raise it.",
      explanationLevel: "general" as const,
      onRestart: () => undefined
    };
    const voiceResponse: AdviceResponse = {
      ...response,
      profile: undefined,
      nearestProfiles: [],
      selectedPhilosopherId: "nietzsche-perspectivism"
    };
    const { rerender } = render(
      <ResultsView {...props} response={voiceResponse} personaMode="philosopher" />
    );
    expect(screen.getByText("Speaking as")).toBeInTheDocument();
    expect(screen.getByText("1844–1900 · Prussia and Germany")).toBeInTheDocument();
    expect(screen.getByText(/ai interpretation/i)).toBeInTheDocument();
    expect(
      screen.getAllByRole("tab", { name: "Speaker" }).length
    ).toBeGreaterThan(0);
    expect(screen.queryByRole("tab", { name: "Coordinates" })).not.toBeInTheDocument();

    rerender(<ResultsView {...props} response={response} personaMode="personalized" />);
    expect(screen.queryByText("Speaking as")).not.toBeInTheDocument();
    expect(
      screen.getAllByRole("tab", { name: "Coordinates" }).length
    ).toBeGreaterThan(0);
  });
});
