import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { AdviceResponse } from "../../shared/contracts";
import { ResultsView } from "./ResultsView";

const response: AdviceResponse = {
  adviceMarkdown: [
    "## Core advice",
    "",
    "Lead with the most grounded version of the truth.",
    "",
    "## Why this advice",
    "",
    "It balances honesty with proportionality.",
    "",
    "## Watch for",
    "",
    "Avoid turning uncertainty into accusation.",
    "",
    "## Next steps",
    "",
    "Confirm what you know before you escalate."
  ].join("\n"),
  profile: {
    outcomesPrinciples: -0.15,
    individualCollective: 0.4,
    reasonIntuition: -0.2
  },
  nearestProfiles: [
    {
      id: "gilligan-care-ethics",
      name: "Care Ethics",
      representative: "Carol Gilligan",
      group: "contemporary",
      voiceStyle: "in-the-spirit",
      voiceBrief: "brief",
      speaker: { years: "born 1936", region: "United States", traditions: "Care ethics" },
      coordinates: {
        outcomesPrinciples: -0.1,
        individualCollective: 0.8,
        reasonIntuition: 0.2
      },
      summary: "Relational and context-aware.",
      exampleConcerns: ["care"],
      distance: 0.3,
      whyItFits: "It stays attentive to harm, trust, and relationships."
    },
    {
      id: "aristotle-virtue-ethics",
      name: "Virtue Ethics",
      representative: "Aristotle",
      group: "ancient",
      voiceStyle: "first-person",
      voiceBrief: "brief",
      speaker: { years: "384–322 BCE", region: "Ancient Greece", traditions: "Virtue ethics" },
      coordinates: {
        outcomesPrinciples: 0.2,
        individualCollective: 0.1,
        reasonIntuition: 0
      },
      summary: "Character-centered.",
      exampleConcerns: ["character"],
      distance: 0.5,
      whyItFits: "It is nearby on practical judgment."
    }
  ],
  safetyMode: "standard",
  modelsUsed: ["openai:gpt-5.4-mini"]
};

describe("ResultsView", () => {
  const originalInnerWidth = window.innerWidth;
  const clientWidthDescriptor = Object.getOwnPropertyDescriptor(
    HTMLElement.prototype,
    "clientWidth"
  );
  const scrollWidthDescriptor = Object.getOwnPropertyDescriptor(
    HTMLElement.prototype,
    "scrollWidth"
  );

  let measuredClientWidth = 1200;
  let measuredScrollWidth = 900;

  beforeEach(() => {
    window.innerWidth = 1280;
    measuredClientWidth = 1200;
    measuredScrollWidth = 900;

    Object.defineProperty(HTMLElement.prototype, "clientWidth", {
      configurable: true,
      get() {
        return this.classList.contains("results-tabs-measure") ? measuredClientWidth : 0;
      }
    });

    Object.defineProperty(HTMLElement.prototype, "scrollWidth", {
      configurable: true,
      get() {
        return this.classList.contains("results-tabs-measure") ? measuredScrollWidth : 0;
      }
    });
  });

  afterEach(() => {
    cleanup();
    window.innerWidth = originalInnerWidth;

    if (clientWidthDescriptor) {
      Object.defineProperty(HTMLElement.prototype, "clientWidth", clientWidthDescriptor);
    }

    if (scrollWidthDescriptor) {
      Object.defineProperty(HTMLElement.prototype, "scrollWidth", scrollWidthDescriptor);
    }
  });

  it.each([
    { models: ["openai:gpt-5.4-mini"], expected: "> Advice model: GPT-5.4 Mini (openai:gpt-5.4-mini)" },
    // Advice saved by an older version of the app can still carry these shapes.
    { models: ["anthropic:claude-haiku-5-5", "openai:gpt-5.4-mini"], expected: "> Advice model: GPT-5.4 Mini (openai:gpt-5.4-mini)" },
    { models: ["local-safety"], expected: "> Generated by: local safety response (no AI model)" }
  ])("exports the actual generation model: $models", async ({ models, expected }) => {
    const write = vi.fn().mockResolvedValue(undefined);
    vi.stubGlobal("showSaveFilePicker", vi.fn().mockResolvedValue({
      createWritable: async () => ({ write, close: async () => undefined })
    }));
    try {
      render(<ResultsView response={{ ...response, modelsUsed: models }} dilemma="A difficult choice"
        explanationLevel="general" personaMode="personalized" onRestart={() => undefined} />);
      fireEvent.click(screen.getByRole("tab", { name: "Export" }));
      fireEvent.click(screen.getByRole("button", { name: "Save as markdown file" }));
      await waitFor(() => expect(write).toHaveBeenCalled());
      const markdown = write.mock.calls[0][0];
      expect(markdown).toContain(expected);
      expect(markdown).not.toContain("Planner model");
    } finally {
      vi.unstubAllGlobals();
    }
  });

  it("switches to the hamburger menu when the tab row overflows", async () => {
    const { container } = render(
      <ResultsView
        response={response}
        dilemma="I heard a rumor about a colleague and do not know whether to raise it."
        explanationLevel="general"
        personaMode="personalized"
        onRestart={() => undefined}
      />
    );

    const desktopNav = container.querySelector(
      "[role=tablist].results-tabs-desktop"
    );
    const mobileNav = container.querySelector("nav.results-tabs-mobile");

    await waitFor(() => {
      expect(screen.queryByRole("button", { name: /^Advice sections/ })).not.toBeInTheDocument();
    });

    expect(screen.getByRole("tab", { name: "Reasoning" })).toBeInTheDocument();
    expect(desktopNav).not.toHaveAttribute("hidden");
    expect(mobileNav).toHaveAttribute("hidden");

    measuredClientWidth = 760;
    measuredScrollWidth = 980;
    fireEvent(window, new Event("resize"));

    await waitFor(() => {
      expect(screen.getByRole("button", { name: /^Advice sections/ })).toBeInTheDocument();
    });

    expect(screen.queryByRole("tab", { name: "Reasoning" })).not.toBeInTheDocument();
    expect(desktopNav).toHaveAttribute("hidden");
    expect(mobileNav).not.toHaveAttribute("hidden");
  });

  describe("section tabs", () => {
    const fiveSections = [
      "## Core advice",
      "",
      "Lead with the truth.",
      "",
      "## Why this advice",
      "",
      "It balances honesty with proportionality.",
      "",
      "## What this answer turns on",
      "",
      "Whether the figures were actually changed.",
      "",
      "## What to watch for",
      "",
      "Avoid accusation.",
      "",
      "## A concrete next step in the next 24 hours",
      "",
      "Write down what you know."
    ].join("\n");

    function renderAdvice(adviceMarkdown: string) {
      return render(
        <ResultsView
          response={{ ...response, adviceMarkdown }}
          dilemma="A difficult choice"
          explanationLevel="general"
          personaMode="personalized"
          onRestart={() => undefined}
        />
      );
    }

    it("puts the new section in its own Key fact tab after Reasoning", () => {
      renderAdvice(fiveSections);
      const names = screen.getAllByRole("tab").map((t) => t.textContent);
      expect(names.slice(0, 5)).toEqual(["Advice", "Reasoning", "Key fact", "Watch for", "Next step"]);

      fireEvent.click(screen.getByRole("tab", { name: "Reasoning" }));
      expect(screen.getByText("It balances honesty with proportionality.")).toBeInTheDocument();
      expect(screen.queryByText("Whether the figures were actually changed.")).not.toBeInTheDocument();

      fireEvent.click(screen.getByRole("tab", { name: "Key fact" }));
      expect(screen.getByRole("heading", { name: "What this answer turns on" })).toBeInTheDocument();
      expect(screen.getByText("Whether the figures were actually changed.")).toBeInTheDocument();
      expect(screen.queryByText("It balances honesty with proportionality.")).not.toBeInTheDocument();

      fireEvent.click(screen.getByRole("tab", { name: "Watch for" }));
      expect(screen.getByText("Avoid accusation.")).toBeInTheDocument();
      fireEvent.click(screen.getByRole("tab", { name: "Next step" }));
      expect(screen.getByText("Write down what you know.")).toBeInTheDocument();
    });

    it("shows no Key fact tab for advice in the old four-section format", () => {
      renderAdvice(response.adviceMarkdown);
      expect(screen.queryByRole("tab", { name: "Key fact" })).not.toBeInTheDocument();
    });

    it("keeps the profile-route heading in the Reasoning tab", () => {
      renderAdvice(
        fiveSections.replace("## Why this advice", "## Why this fits your ethical profile")
      );
      fireEvent.click(screen.getByRole("tab", { name: "Reasoning" }));
      expect(screen.getByText("It balances honesty with proportionality.")).toBeInTheDocument();
      expect(screen.queryByText("Whether the figures were actually changed.")).not.toBeInTheDocument();
    });

    it("includes the new section in the export when present", () => {
      renderAdvice(fiveSections);
      fireEvent.click(screen.getByRole("tab", { name: "Export" }));
      const preview = document.querySelector(".export-preview pre")?.textContent ?? "";
      expect(preview).toContain("## What this answer turns on");
      expect(preview).toContain("Whether the figures were actually changed.");
      expect(preview.indexOf("## Why this advice")).toBeLessThan(preview.indexOf("## What this answer turns on"));
      expect(preview.indexOf("## What this answer turns on")).toBeLessThan(preview.indexOf("## What to watch for"));
    });

    it("leaves the section out of the export for old advice", () => {
      renderAdvice(response.adviceMarkdown);
      fireEvent.click(screen.getByRole("tab", { name: "Export" }));
      expect(document.querySelector(".export-preview pre")?.textContent ?? "").not.toContain("turns on");
    });
  });

  it("shows the speaker card and speaker tab only when a philosopher voice was used", async () => {
    const props = {
      dilemma: "I heard a rumor about a colleague and do not know whether to raise it.",
      explanationLevel: "general" as const,
      onRestart: () => undefined
    };
    const voiceResponse: AdviceResponse = {
      ...response,
      profile: undefined,
      nearestProfiles: [],
      selectedPhilosopherId: "nietzsche-perspectivism"
    };
    const { rerender } = render(
      <ResultsView {...props} response={voiceResponse} personaMode="philosopher" />
    );
    expect(screen.getByText("Speaking as")).toBeInTheDocument();
    expect(screen.getByText("1844–1900 · Prussia and Germany")).toBeInTheDocument();
    expect(screen.getByText(/ai interpretation/i)).toBeInTheDocument();
    expect(
      screen.getAllByRole("tab", { name: "Speaker" }).length
    ).toBeGreaterThan(0);
    expect(screen.queryByRole("tab", { name: "Coordinates" })).not.toBeInTheDocument();

    fireEvent.click(screen.getAllByRole("tab", { name: "Speaker" })[0]);
    expect(screen.getByText("Moral foundations")).toBeInTheDocument();
    expect(screen.getByText("My own people first")).toBeInTheDocument();
    expect(screen.getByText(/average of ratings from three AI models/i)).toBeInTheDocument();

    fireEvent.click(screen.getAllByRole("tab", { name: "Export" })[0]);
    const exported = document.querySelector(".export-preview pre")?.textContent ?? "";
    expect(exported).toContain("**Moral foundations** (0 to 10):");
    expect(exported).toContain("Everyone equally to My own people first");

    rerender(<ResultsView {...props} response={response} personaMode="personalized" />);
    expect(screen.queryByText("Speaking as")).not.toBeInTheDocument();
    expect(
      screen.getAllByRole("tab", { name: "Coordinates" }).length
    ).toBeGreaterThan(0);
  });
});
